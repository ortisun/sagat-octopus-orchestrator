//! Markdown from the contracts. Pure functions of the documents they are given, so that the output
//! is the same on every machine.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use serde_json::Value;

const GENERATED: &str = "<!-- Generated by `cargo test -p sagat-tests --test contract_developer_experience`; \
SAGAT_DOCS_BLESS=1 rewrites it. Do not edit. -->";

fn cell(text: &str) -> String {
    text.replace('|', "\\|").replace('\n', " ")
}

/// The operations of an OpenAPI document, by tag, each with what a caller wants to see first.
#[must_use]
pub fn api_reference(openapi: &Value, source: &str) -> String {
    let mut by_tag: BTreeMap<String, Vec<(String, usize, String)>> = BTreeMap::new();
    // The operations that take no token: a `security: []` of their own.
    let mut open: Vec<String> = Vec::new();
    let methods = ["get", "post", "put", "patch", "delete"];
    let mut count = 0usize;
    for (path, item) in openapi["paths"].as_object().into_iter().flatten() {
        for (order, method) in methods.iter().enumerate() {
            let Some(operation) = item.get(*method) else {
                continue;
            };
            count += 1;
            let tag = operation["tags"][0].as_str().unwrap_or("Other").to_owned();
            if operation["security"].as_array().is_some_and(Vec::is_empty) {
                open.push(format!("`{} {}`", method.to_uppercase(), path));
            }
            let success = operation["responses"]
                .as_object()
                .into_iter()
                .flatten()
                .map(|(code, _)| code.as_str())
                .filter(|code| code.starts_with('2'))
                .min()
                .unwrap_or("-");
            let keyed = operation["parameters"]
                .as_array()
                .into_iter()
                .flatten()
                .any(|p| {
                    p["$ref"]
                        .as_str()
                        .is_some_and(|r| r.ends_with("IdempotencyKey"))
                        || p["name"]
                            .as_str()
                            .is_some_and(|n| n.eq_ignore_ascii_case("idempotency-key"))
                });
            let feature = operation["x-implemented"].as_str().unwrap_or("001");
            let mut row = String::new();
            let _ = write!(
                row,
                "| `{}` | `{} {}` | {} | {} | {} | {} |",
                cell(operation["operationId"].as_str().unwrap_or("?")),
                method.to_uppercase(),
                cell(path),
                cell(operation["summary"].as_str().unwrap_or("")),
                success,
                if keyed { "yes" } else { "" },
                feature,
            );
            by_tag
                .entry(tag)
                .or_default()
                .push((path.clone(), order, row));
        }
    }
    let mut out = String::new();
    let _ = writeln!(out, "# REST API reference\n\n{GENERATED}\n");
    let _ = writeln!(
        out,
        "Made from `{source}` (version {}): {count} operations in {} groups. The full contract \
         (parameters, bodies, schemas, errors) is that file; this page is the map of it. Every call \
         takes `Authorization: Bearer <token>` (the tenant is the token's) except {}. The operations \
         that take an `Idempotency-Key` are marked: a repeat with the same key and body answers the \
         first result.\n",
        openapi["info"]["version"].as_str().unwrap_or("?"),
        by_tag.len(),
        if open.is_empty() {
            "none".to_owned()
        } else {
            open.sort();
            format!("these, which take no bearer token: {}", open.join(", "))
        }
    );
    for (tag, mut rows) in by_tag {
        rows.sort_by(|a, b| (&a.0, a.1).cmp(&(&b.0, b.1)));
        let _ = writeln!(out, "## {tag}\n");
        let _ = writeln!(
            out,
            "| Operation | Request | Summary | OK | Idempotency-Key | Feature |\n|---|---|---|---|---|---|"
        );
        for (_, _, row) in rows {
            let _ = writeln!(out, "{row}");
        }
        out.push('\n');
    }
    out.trim_end().to_owned() + "\n"
}

/// How a type reads: a reference is a link only to a heading this page has.
fn type_of(schema: &Value, headings: &BTreeSet<String>) -> String {
    if let Some(reference) = schema["$ref"].as_str() {
        let name = reference.rsplit('/').next().unwrap_or("?");
        return if headings.contains(name) {
            format!("[`{name}`](#{name})")
        } else {
            format!("`{name}`")
        };
    }
    if let Some(constant) = schema.get("const") {
        return format!("`{constant}`");
    }
    if let Some(values) = schema["enum"].as_array() {
        let names: Vec<String> = values.iter().map(|v| format!("`{v}`")).collect();
        return format!("one of {}", names.join(", "));
    }
    match schema["type"].as_str() {
        Some("array") => format!("array of {}", type_of(&schema["items"], headings)),
        Some(other) => other.to_owned(),
        None => "any".to_owned(),
    }
}

fn limits(schema: &Value) -> String {
    let mut parts = Vec::new();
    for (key, label) in [
        ("minimum", "min"),
        ("maximum", "max"),
        ("minLength", "min length"),
        ("maxLength", "max length"),
        ("minItems", "min items"),
        ("maxItems", "max items"),
    ] {
        if let Some(v) = schema.get(key) {
            parts.push(format!("{label} {v}"));
        }
    }
    if let Some(pattern) = schema["pattern"].as_str() {
        parts.push(format!("pattern `{}`", pattern.replace('|', "\\|")));
    }
    if parts.is_empty() {
        String::new()
    } else {
        format!(" ({})", parts.join(", "))
    }
}

/// The rows of a table of fields: one for each property, and the properties of an object (or of
/// the objects of an array) under it, with the path in front of the name.
fn rows(schema: &Value, prefix: &str, headings: &BTreeSet<String>, out: &mut String) {
    let required: Vec<&str> = schema["required"]
        .as_array()
        .into_iter()
        .flatten()
        .filter_map(Value::as_str)
        .collect();
    for (name, property) in schema["properties"].as_object().into_iter().flatten() {
        let _ = writeln!(
            out,
            "| `{prefix}{name}` | {}{} | {} | {} |",
            type_of(property, headings),
            limits(property),
            if required.contains(&name.as_str()) {
                "yes"
            } else {
                ""
            },
            cell(property["description"].as_str().unwrap_or(""))
        );
        if property["properties"].is_object() {
            rows(property, &format!("{prefix}{name}."), headings, out);
        } else if property["items"]["properties"].is_object() {
            rows(
                &property["items"],
                &format!("{prefix}{name}[]."),
                headings,
                out,
            );
        }
    }
}

fn fields(schema: &Value, headings: &BTreeSet<String>, out: &mut String) {
    let _ = writeln!(
        out,
        "| Field | Type | Required | Description |\n|---|---|---|---|"
    );
    rows(schema, "", headings, out);
    out.push('\n');
}

/// The workflow document, field by field, from its JSON Schema.
#[must_use]
pub fn workflow_reference(schema: &Value, source: &str) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "# Workflow document reference\n\n{GENERATED}\n");
    let _ = writeln!(
        out,
        "Made from `{source}`. A workflow is one JSON (or YAML) object: this page lists its fields and the \
         fields of each kind of node. The schema checks the shape; the platform's codec checks more \
         (the graph, the expressions, the references between nodes), and `sagat workflow validate` runs \
         the codec: [errors.md](../quickstarts/errors.md) says what each of its findings means. \
         Some shapes are reserved for capabilities still under development; schema acceptance alone \
         does not make a node runnable. See the [capability validation report](../../specs/014-workflow-primitives/validation-report.md).\n"
    );
    let defs = schema["$defs"].as_object();
    let kinds: Vec<&str> = schema["$defs"]["node"]["oneOf"]
        .as_array()
        .into_iter()
        .flatten()
        .filter_map(|r| r["$ref"].as_str())
        .filter_map(|r| r.rsplit('/').next())
        .collect();
    // The headings this page has: every definition but `node`, which is the choice among the kinds.
    let headings: BTreeSet<String> = defs
        .into_iter()
        .flatten()
        .map(|(name, _)| name.clone())
        .filter(|name| name != "node")
        .collect();
    let _ = writeln!(out, "## The document\n");
    fields(schema, &headings, &mut out);
    let _ = writeln!(out, "## Nodes\n");
    let _ = writeln!(
        out,
        "Every node has the fields below; each kind adds its own. The kinds: {}.\n",
        kinds
            .iter()
            .map(|k| format!("[`{k}`](#{k})"))
            .collect::<Vec<_>>()
            .join(", ")
    );
    if let Some(base) = defs.and_then(|d| d.get("base")) {
        let _ = writeln!(out, "### base\n");
        fields(base, &headings, &mut out);
    }
    for kind in &kinds {
        let Some(def) = defs.and_then(|d| d.get(*kind)) else {
            continue;
        };
        let own = def["allOf"]
            .as_array()
            .and_then(|parts| parts.iter().find(|p| p.get("properties").is_some()))
            .unwrap_or(def);
        let _ = writeln!(out, "### {kind}\n");
        fields(own, &headings, &mut out);
    }
    let _ = writeln!(out, "## Other shapes\n");
    for (name, def) in defs.into_iter().flatten() {
        if kinds.contains(&name.as_str()) || name == "node" || name == "base" {
            continue;
        }
        let _ = writeln!(out, "### {name}\n");
        if def.get("properties").is_some() {
            fields(def, &headings, &mut out);
        } else {
            let _ = writeln!(out, "{}\n", type_of(def, &headings));
        }
    }
    out.trim_end().to_owned() + "\n"
}

/// The tool's help text, as the tool prints it.
#[must_use]
pub fn cli_reference(usage: &str) -> String {
    format!(
        "# `sagat` command reference\n\n{GENERATED}\n\nThe text below is what `sagat help` prints, taken from the \
         tool itself. [The quickstart](../quickstarts/README.md) shows the commands in use.\n\n```text\n{}\n```\n",
        usage.trim_end()
    )
}
