// Copies what the SDKs share with the repository: the worker protocol and the error catalog (as a
// module). `npm test` has a test that fails when the copies are behind.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..', '..');

writeFileSync(
  join(here, '..', 'proto', 'worker.proto'),
  readFileSync(join(root, 'specs', '001-platform-foundation', 'contracts', 'worker.proto')),
);

const catalog = JSON.parse(readFileSync(join(root, 'sdks', 'error-catalog.json'), 'utf8'));
mkdirSync(join(here, '..', 'src'), { recursive: true });
writeFileSync(
  join(here, '..', 'src', 'catalog.ts'),
  `// Generated by scripts/sync-shared.mjs from sdks/error-catalog.json. Do not edit.\n` +
    `export interface CatalogEntry {\n  code: string;\n  origin: 'rest' | 'worker' | 'sdk';\n  http: number[];\n  grpc: string;\n  retryable: boolean;\n  remediation: string;\n}\n\n` +
    `export const CATALOG: readonly CatalogEntry[] = ${JSON.stringify(catalog.errors, null, 2)} as const;\n`,
);
