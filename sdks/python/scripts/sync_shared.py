"""Copies what the SDKs share with the repository and regenerates what is derived from it.

* ``proto/worker.proto`` is a copy of ``specs/001-platform-foundation/contracts/worker.proto``.
* ``sagat_octopus_orchestrator/_proto/worker_pb2*.py`` are generated from that copy with ``grpcio-tools``
  and committed, so that a consumer needs no ``protoc``.
* ``sagat_octopus_orchestrator/_catalog.py`` is the error catalog ``sdks/error-catalog.json`` as Python.

``python scripts/sync_shared.py`` rewrites them; ``--check`` only reports whether they are current (the unit
tests do the same). ``generate_proto`` / ``render_catalog`` are what the tests call.
"""

from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path
from typing import Any

PACKAGE_ROOT = Path(__file__).resolve().parent.parent
REPOSITORY_ROOT = PACKAGE_ROOT.parent.parent
CONTRACT_PROTO = REPOSITORY_ROOT / "specs" / "001-platform-foundation" / "contracts" / "worker.proto"
CONTRACT_CATALOG = REPOSITORY_ROOT / "sdks" / "error-catalog.json"
PROTO_COPY = PACKAGE_ROOT / "proto" / "worker.proto"
PROTO_PACKAGE = "sagat_octopus_orchestrator/_proto"
GENERATED = ("worker_pb2.py", "worker_pb2.pyi", "worker_pb2_grpc.py")
CATALOG_MODULE = PACKAGE_ROOT / "sagat_octopus_orchestrator" / "_catalog.py"


def generate_proto(proto: bytes, out: Path) -> None:
    """Runs protoc over ``proto`` (as ``sagat_octopus_orchestrator/_proto/worker.proto``) into ``out``."""
    from grpc_tools import protoc  # a development dependency: only the codegen needs it

    with tempfile.TemporaryDirectory() as scratch:
        root = Path(scratch)
        source = root / PROTO_PACKAGE / "worker.proto"
        source.parent.mkdir(parents=True)
        source.write_bytes(proto)
        code = protoc.main(
            [
                "grpc_tools.protoc",
                f"-I{root}",
                f"--python_out={root}",
                f"--pyi_out={root}",
                f"--grpc_python_out={root}",
                str(source.relative_to(root)),
            ]
        )
        if code != 0:
            raise SystemExit(f"protoc failed with {code}")
        out.mkdir(parents=True, exist_ok=True)
        for name in GENERATED:
            (out / name).write_bytes((root / PROTO_PACKAGE / name).read_bytes())


def render_catalog(catalog: dict[str, Any]) -> str:
    """The Python module that embeds the error catalog."""
    lines = [
        '"""Generated by scripts/sync_shared.py from sdks/error-catalog.json. Do not edit."""',
        "",
        "from __future__ import annotations",
        "",
        "from dataclasses import dataclass",
        "from typing import Final, Literal",
        "",
        "",
        "@dataclass(frozen=True)",
        "class CatalogEntry:",
        "    code: str",
        '    origin: Literal["rest", "worker", "sdk"]',
        "    http: tuple[int, ...]",
        "    grpc: str",
        "    retryable: bool",
        "    remediation: str",
        "",
        "",
        "CATALOG: Final[tuple[CatalogEntry, ...]] = (",
    ]
    for entry in catalog["errors"]:
        lines += [
            "    CatalogEntry(",
            f"        code={entry['code']!r},",
            f"        origin={entry['origin']!r},",
            f"        http={tuple(entry['http'])!r},",
            f"        grpc={entry['grpc']!r},",
            f"        retryable={entry['retryable']!r},",
            f"        remediation={entry['remediation']!r},",
            "    ),",
        ]
    lines += [")", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    check = "--check" in argv
    proto = CONTRACT_PROTO.read_bytes()
    catalog = json.loads(CONTRACT_CATALOG.read_text(encoding="utf-8"))
    module = render_catalog(catalog)
    stale: list[str] = []

    if not PROTO_COPY.exists() or PROTO_COPY.read_bytes() != proto:
        stale.append(str(PROTO_COPY.relative_to(PACKAGE_ROOT)))
    if not CATALOG_MODULE.exists() or CATALOG_MODULE.read_text(encoding="utf-8") != module:
        stale.append(str(CATALOG_MODULE.relative_to(PACKAGE_ROOT)))
    with tempfile.TemporaryDirectory() as scratch:
        generate_proto(proto, Path(scratch))
        target = PACKAGE_ROOT / "sagat_octopus_orchestrator" / "_proto"
        for name in GENERATED:
            fresh = (Path(scratch) / name).read_bytes()
            if not (target / name).exists() or (target / name).read_bytes() != fresh:
                stale.append(f"sagat_octopus_orchestrator/_proto/{name}")
                if not check:
                    target.mkdir(parents=True, exist_ok=True)
                    (target / name).write_bytes(fresh)
    if check:
        if stale:
            print("behind the repository (run `python scripts/sync_shared.py`): " + ", ".join(stale), file=sys.stderr)
            return 1
        return 0
    PROTO_COPY.parent.mkdir(parents=True, exist_ok=True)
    PROTO_COPY.write_bytes(proto)
    CATALOG_MODULE.write_text(module, encoding="utf-8")
    (PACKAGE_ROOT / "sagat_octopus_orchestrator" / "_proto" / "__init__.py").touch()
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
